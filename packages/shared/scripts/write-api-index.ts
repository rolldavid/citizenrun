import { readdir, writeFile } from 'node:fs/promises';
import { join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

/** The folder Orval writes the generated client into. */
export const API_DIR = resolve(import.meta.dirname, '../src/api');

/** The header every generated client file starts with, as Orval writes it from `orval.config.ts`. */
export const GENERATED_HEADER = '/**\n * Generated by pnpm gen:api. Do not edit by hand.\n */\n';

/** The text of `src/api/index.ts`: the header, one re-export per tag folder (sorted), then the models. */
export function apiIndexText(tags: readonly string[]): string {
  const lines = [...tags]
    .sort((a, b) => (a < b ? -1 : a > b ? 1 : 0))
    .map((tag) => `export * from './${tag}/${tag}.ts';`);
  return `${GENERATED_HEADER}${[...lines, "export * from './model/index.ts';"].join('\n')}\n`;
}

/** The tag folders Orval wrote: every folder under `src/api/` except `model`. */
export async function tagFolders(dir: string): Promise<string[]> {
  const entries = await readdir(dir, { withFileTypes: true });
  return entries
    .filter((entry) => entry.isDirectory() && entry.name !== 'model')
    .map((entry) => entry.name);
}

export async function main(): Promise<void> {
  await writeFile(join(API_DIR, 'index.ts'), apiIndexText(await tagFolders(API_DIR)), 'utf8');
}

const entry = process.argv[1];
if (entry !== undefined && resolve(entry) === fileURLToPath(import.meta.url)) {
  await main();
}
