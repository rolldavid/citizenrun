const FORBIDDEN = new Set(FORBIDDEN_LOG_FIELDS);

/** True when `key`, lower-cased and without `_` and `-`, is a forbidden log field. */
export function isForbiddenLogField(key: string): boolean {
  return FORBIDDEN.has(key.toLowerCase().replace(/[_-]/g, ''));
}
