/** The overrides of the Candidacy factory: any column, and the election's date for the key. */
export type CandidacyOverrides = Partial<NewCandidacyRow> & { electionDate?: string };

/**
 * A `filed` candidacy from the source `fixture`, keyed
 * `ZZ|fixture|<election date>|fixture office|Fixture Person<seq>`, its id the civic id of that
 * key, the raw name `Fixture Person<seq>` in its parts, an empty status history and overrides, and
 * the party, filing date, source and match confidence null. insertCandidacy takes the name from
 * the person and the date from the election.
 */
export function makeCandidacy(
  overrides: CandidacyOverrides = {},
  ctx: FactoryContext = defaultFactoryContext(),
): NewCandidacyRow {
  const { electionDate, ...columns } = overrides;
  const seq = nextSequence();
  const filingKey =
    columns.filingKey ??
    fixtureFilingKey('fixture', electionDate ?? utcDate(ctx.now), `Fixture Person${String(seq)}`);
  return {
    source: 'fixture',
    personId: civicId('people', fixtureSourceKey('people', seq)),
    electionId: civicId('elections', fixtureSourceKey('elections', seq)),
    party: null,
    status: 'filed',
    statusHistory: [],
    filedOn: null,
    rawName: `Fixture Person${String(seq)}`,
    firstName: 'Fixture',
    lastName: `Person${String(seq)}`,
    sourceUrl: null,
    matchConfidence: null,
    overrides: {},
    ...columns,
    id: columns.id ?? civicId('candidacies', filingKey),
    filingKey,
  };
}

/**
 * Writes a candidacy and, in the same transaction, its first `candidacy_filings` row (the first
 * key is a row too), creating the person and the election when not given. The raw name and its
 * parts are the person's unless the overrides set them. Returns the stored candidacy.
 */
export async function insertCandidacy(
  db: Db | Tx,
  overrides: CandidacyOverrides = {},
  ctx: FactoryContext = defaultFactoryContext(),
): Promise<CandidacyRow> {
  return db.transaction(async (tx) => {
    let person: PersonRow | undefined;
    if (overrides.personId === undefined) {
      person = await insertPerson(tx);
    } else {
      [person] = await tx.select().from(people).where(eq(people.id, overrides.personId));
    }
    if (person === undefined) {
      throw new Error('The candidacy factory found no person.');
    }
    const electionId = overrides.electionId ?? (await insertElection(tx, {}, ctx)).id;
    const electionDate = overrides.electionDate ?? (await electionDateOf(tx, electionId));
    const [row] = await tx
      .insert(candidacies)
      .values(
        makeCandidacy(
          {
            rawName: person.name,
            firstName: person.firstName,
            lastName: person.lastName,
            ...overrides,
            personId: person.id,
            electionId,
            electionDate,
          },
          ctx,
        ),
      )
      .returning();
    if (row === undefined) {
      throw new Error('The candidacies insert returned no row.');
    }
    await tx.insert(candidacyFilings).values({
      filingKey: row.filingKey,
      candidacyId: row.id,
      source: row.source,
      status: row.status,
    });
    return row;
  });
}

/** The overrides of the CandidacyFiling factory: any column, and the election's date for the key. */
export type CandidacyFilingOverrides = Partial<NewCandidacyFilingRow> & { electionDate?: string };

/**
 * A second `filed` filing row of a candidacy, from the source `fixture-second`, keyed
 * `ZZ|fixture-second|<election date>|fixture office|Fixture Person<seq>`, not gone. Without a
 * `candidacyId` the row names a fixture key's civic id; insertCandidacyFiling then creates one.
 */
export function makeCandidacyFiling(
  overrides: CandidacyFilingOverrides = {},
  ctx: FactoryContext = defaultFactoryContext(),
): NewCandidacyFilingRow {
  const { electionDate, ...columns } = overrides;
  const seq = nextSequence();
  return {
    candidacyId: civicId('candidacies', fixtureSourceKey('candidacies', seq)),
    source: 'fixture-second',
    status: 'filed',
    goneAt: null,
    ...columns,
    filingKey:
      columns.filingKey ??
      fixtureFilingKey(
        'fixture-second',
        electionDate ?? utcDate(ctx.now),
        `Fixture Person${String(seq)}`,
      ),
  };
}

/** Writes makeCandidacyFiling, creating its candidacy when none is given; returns the stored row. */
export async function insertCandidacyFiling(
  db: Db | Tx,
  overrides: CandidacyFilingOverrides = {},
  ctx: FactoryContext = defaultFactoryContext(),
): Promise<CandidacyFilingRow> {
  return db.transaction(async (tx) => {
    const candidacyId = overrides.candidacyId ?? (await insertCandidacy(tx, {}, ctx)).id;
    let electionDate = overrides.electionDate;
    if (electionDate === undefined) {
      const [candidacy] = await tx
        .select({ electionId: candidacies.electionId })
        .from(candidacies)
        .where(eq(candidacies.id, candidacyId));
      if (candidacy === undefined) {
        throw new Error('The candidacy filing factory found no candidacy.');
      }
      electionDate = await electionDateOf(tx, candidacy.electionId);
    }
    const [row] = await tx
      .insert(candidacyFilings)
      .values(makeCandidacyFiling({ ...overrides, candidacyId, electionDate }, ctx))
      .returning();
    if (row === undefined) {
      throw new Error('The candidacy_filings insert returned no row.');
    }
    return row;
  });
}

/**
 * The allow-listed `raw` object of a filing row (D-084) with fixture values: the name
 * `Fixture Unmatched <seq>` in its parts, a fixture office and county, `filed`, the election date
 * and a fixture list link; every other key null. Never an address, a phone or an email.
 */
function fixtureUnmatchedRaw(seq: number, electionDate: string): Record<string, string | null> {
  return {
    name: `Fixture Unmatched ${String(seq)}`,
    first_name: 'Fixture',
    middle_name: null,
    last_name: 'Unmatched',
    suffix: null,
    office_text: 'Fixture Office',
    district_text: null,
    jurisdiction_text: 'Fixture County',
    party: null,
    filed_on: null,
    status: 'filed',
    election_date: electionDate,
    source_url: 'https://example.test/fixture-list',
  };
}

/**
 * An open filing row the matcher could not place, from the source `fixture` in state `ZZ`, keyed
 * `ZZ|fixture|<UTC date of ctx.now>|fixture office|Fixture Unmatched <seq>`, its id the civic id
 * of that key, `raw` the allow-listed fixture object, and the reason, suggestions, features,
 * resolution, office, person, decider and resolution time null.
 */
export function makeUnmatchedFiling(
  overrides: Partial<NewUnmatchedFilingRow> = {},
  ctx: FactoryContext = defaultFactoryContext(),
): NewUnmatchedFilingRow {
  const seq = nextSequence();
  const electionDate = utcDate(ctx.now);
  const filingKey =
    overrides.filingKey ??
    fixtureFilingKey('fixture', electionDate, `Fixture Unmatched ${String(seq)}`);
  return {
    kind: 'filing',
    source: 'fixture',
    state: 'ZZ',
    raw: fixtureUnmatchedRaw(seq, electionDate),
    reason: null,
    suggested: null,
    features: null,
    resolution: null,
    officeId: null,
    personId: null,
    decidedBy: null,
    resolvedAt: null,
    ...overrides,
    id: overrides.id ?? civicId('unmatched_filings', filingKey),
    filingKey,
  };
}

/** Writes makeUnmatchedFiling(overrides) and returns the stored row. */
export async function insertUnmatchedFiling(
  db: Db | Tx,
  overrides: Partial<NewUnmatchedFilingRow> = {},
  ctx: FactoryContext = defaultFactoryContext(),
): Promise<UnmatchedFilingRow> {
  const [row] = await db
    .insert(unmatchedFilings)
    .values(makeUnmatchedFiling(overrides, ctx))
    .returning();
  if (row === undefined) {
    throw new Error('The unmatched_filings insert returned no row.');
  }
  return row;
}
