// The people factories (TEST-harness-factories). `name_key` is generated by the
// database from the name parts. Filing rows hold the allow-listed fields only (D-084).

/**
 * A person `Fixture Person<seq>` (first name `Fixture`, last name `Person<seq>`), slug
 * `fixture-person-<seq>`, keyed `fixture:people:<seq>`, not roster-only, with empty overrides and
 * every other column null, `origin` included.
 */
export function makePerson(overrides: Partial<NewPersonRow> = {}): NewPersonRow {
  const seq = nextSequence();
  const sourceKey = overrides.sourceKey ?? fixtureSourceKey('people', seq);
  return {
    firstName: 'Fixture',
    lastName: `Person${String(seq)}`,
    name: `Fixture Person${String(seq)}`,
    slug: `fixture-person-${String(seq)}`,
    rosterOnly: false,
    overrides: {},
    origin: null,
    ...overrides,
    id: overrides.id ?? civicId('people', sourceKey),
    sourceKey,
  };
}

/** Writes makePerson(overrides) and returns the stored row. */
export async function insertPerson(
  db: Db | Tx,
  overrides: Partial<NewPersonRow> = {},
): Promise<PersonRow> {
  const [row] = await db.insert(people).values(makePerson(overrides)).returning();
  if (row === undefined) {
    throw new Error('The people insert returned no row.');
  }
  return row;
}

/** The UTC calendar date of `at`, as `YYYY-MM-DD`. */
function utcDate(at: Date): string {
  return at.toISOString().slice(0, 10);
}

/** A filing key of the shape `<state>|<source>|<election date>|<office text>|<name>`. */
function fixtureFilingKey(source: string, electionDate: string, name: string): string {
  return `ZZ|${source}|${electionDate}|fixture office|${name}`;
}

/** The election date of an election, or a refusal when the election does not exist. */
async function electionDateOf(db: Db | Tx, electionId: string): Promise<string> {
  const [election] = await db
    .select({ electionDate: elections.electionDate })
    .from(elections)
    .where(eq(elections.id, electionId));
  if (election === undefined) {
    throw new Error('The candidacy factory found no election.');
  }
  return election.electionDate;
}

/** An alias `Fixture Alias <seq>` of a person. Without a `personId` the row names a fixture key's civic id. */
export function makePersonAlias(overrides: Partial<NewPersonAliasRow> = {}): NewPersonAliasRow {
  const seq = nextSequence();
  return {
    personId: civicId('people', fixtureSourceKey('people', seq)),
    alias: `Fixture Alias ${String(seq)}`,
    ...overrides,
  };
}

/** Writes makePersonAlias, creating its person when none is given; returns the stored row. */
export async function insertPersonAlias(
  db: Db | Tx,
  overrides: Partial<NewPersonAliasRow> = {},
): Promise<PersonAliasRow> {
  return db.transaction(async (tx) => {
    const personId = overrides.personId ?? (await insertPerson(tx)).id;
    const [row] = await tx
      .insert(personAliases)
      .values(makePersonAlias({ ...overrides, personId }))
      .returning();
    if (row === undefined) {
      throw new Error('The person_aliases insert returned no row.');
    }
    return row;
  });
}

