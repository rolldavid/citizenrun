/** The wordmark or the two letters as a drawing of its own, `capHeight` high, in one color. */
export function WordmarkSvg(props: WordmarkSvgProps): JSX.Element {
  const data = props.variant === 'wordmark' ? WORDMARK : MONOGRAM;
  return createElement(
    Svg,
    {
      width: round1((props.capHeight * data.width) / data.height),
      height: props.capHeight,
      viewBox: `0 0 ${String(data.width)} ${String(data.height)}`,
      ...svgRootProps(),
    },
    createElement(Path, { d: data.d, fill: props.fill }),
  );
}
