import { mkdir, readdir, readFile, rm, writeFile } from 'node:fs/promises';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { transform } from '@svgr/core';
import { format, resolveConfig } from 'prettier';
import { optimize } from 'svgo';
import { assertNever, ISSUE_IDS } from '@citizenrun/shared';
import { lintArtSource } from './art-lint.ts';
import type { ArtViolation } from './art-lint.ts';
import { ART_GROUPS, ART_RULES } from './art-rules.ts';
import type { ArtGroup, ArtGroupRules, SentinelRole } from './art-rules.ts';

// CARD-art-gen (D-276): lints every art source, then turns each into a typed component through SVGO
// and SVGR, and writes the generated folder with its prop types and index. `pnpm cards:gen` runs it.

export type GenerateResult = {
  written: readonly string[];
  removed: readonly string[];
  violations: readonly ArtViolation[];
};

const HEADER = '// Generated by pnpm cards:gen. Do not edit.';
const PRIMITIVES = '@citizenrun/cards/primitives';
const GENERATED = 'src/generated';
const SCRIPT_PATH = fileURLToPath(import.meta.url);

/** One source file of a group, read and named. */
type Source = { group: ArtGroup; id: string; fileName: string; text: string };

// The JSX nodes the template touches, as Babel builds them.
type JsxName = { type: 'JSXIdentifier'; name: string };
type JsxElement = {
  type: 'JSXElement';
  openingElement: { name: JsxName; attributes: unknown[] };
  closingElement: { name: JsxName } | null;
  children: unknown[];
};
type TemplateVariables = { componentName: string; jsx: JsxElement };
/** SVGR passes Babel's `template.smart(...).ast`, which takes a template literal's strings and values. */
type TemplateApi = { tpl: (code: readonly string[], ...values: unknown[]) => unknown };

function isJsxElement(node: unknown): node is JsxElement {
  return typeof node === 'object' && node !== null && 'type' in node && node.type === 'JSXElement';
}

/** Whether a file system error says the path does not exist. */
function isMissing(error: unknown): boolean {
  return error instanceof Error && 'code' in error && error.code === 'ENOENT';
}

/** `rent-housing` gives `RentHousing`, `data-centers-ai` gives `DataCentersAi`. */
export function componentNameOf(id: string): string {
  return id
    .split('-')
    .map((part) => part.charAt(0).toUpperCase() + part.slice(1))
    .join('');
}

/** The primitive a source element becomes: its name with a capital, as react-native-svg names it. */
function primitiveOf(element: string): string {
  return element.charAt(0).toUpperCase() + element.slice(1);
}

/** The role names of a group's sentinels, in the order the rules list them. */
function rolesOf(rules: ArtGroupRules): readonly SentinelRole[] {
  return [...new Set(Object.values(rules.sentinels))];
}

/**
 * The SVGR template: it drops SVGR's own imports, renames the root to `G` with no attributes, gives the
 * children their primitive names, and writes a named component that imports only the primitives it
 * draws and its props type. SVGR runs the template before its react-native pass, which converts only
 * the descendants of an `svg` root, so the template names the children itself.
 */
function artTemplate(rules: ArtGroupRules) {
  const allowed = new Set(Object.keys(rules.elements));
  return (variables: TemplateVariables, { tpl }: TemplateApi): unknown => {
    const root = variables.jsx;
    const used = new Set<string>(['G']);
    root.openingElement.name = { type: 'JSXIdentifier', name: 'G' };
    root.openingElement.attributes = [];
    if (root.closingElement !== null) {
      root.closingElement.name = { type: 'JSXIdentifier', name: 'G' };
    }
    for (const child of root.children) {
      if (!isJsxElement(child)) continue;
      const element = child.openingElement.name.name;
      if (!allowed.has(element)) {
        throw new Error(`${variables.componentName}: SVGO left a ${element} element`);
      }
      const name = primitiveOf(element);
      used.add(name);
      child.openingElement.name = { type: 'JSXIdentifier', name };
      if (child.closingElement !== null) {
        child.closingElement.name = { type: 'JSXIdentifier', name };
      }
    }
    const imports = [...used].sort((a, b) => a.localeCompare(b, 'en')).join(', ');
    return tpl(
      [
        `import { ${imports} } from '${PRIMITIVES}';\n` +
          `import type { ${rules.propsType} } from '../types.ts';\n\n` +
          `export function ${variables.componentName}(props: ${rules.propsType}) {\n  return (`,
        `);\n}\n`,
      ],
      root,
    );
  };
}

async function prettierOptions(): Promise<Record<string, unknown>> {
  const options = await resolveConfig(SCRIPT_PATH);
  if (options === null) {
    throw new Error('no Prettier configuration was found for the generator');
  }
  return options;
}

async function formatTs(
  code: string,
  outputPath: string,
  options: Record<string, unknown>,
): Promise<string> {
  return format(`${HEADER}\n${code}`, { ...options, filepath: outputPath });
}

async function filesOf(folder: string): Promise<string[]> {
  try {
    const entries = await readdir(folder, { withFileTypes: true });
    return entries
      .filter((entry) => entry.isFile() && !entry.name.startsWith('.'))
      .map((entry) => entry.name)
      .sort((a, b) => a.localeCompare(b, 'en'));
  } catch (error) {
    if (isMissing(error)) return [];
    throw error;
  }
}

/** Converts one source to the formatted text of its component. */
async function componentOf(
  source: Source,
  options: Record<string, unknown>,
  outputPath: string,
): Promise<string> {
  const rules = ART_RULES[source.group];
  const optimised = optimize(source.text, {
    multipass: false,
    plugins: [{ name: 'preset-default', params: { overrides: { convertColors: false } } }],
  }).data;
  const replaceAttrValues = Object.fromEntries(
    Object.entries(rules.sentinels).map(([hex, role]) => [hex, `{props.${role}}`]),
  );
  const code = await transform(
    optimised,
    {
      plugins: ['@svgr/plugin-jsx'],
      typescript: true,
      native: true,
      svgo: false,
      expandProps: false,
      dimensions: false,
      jsxRuntime: 'automatic',
      replaceAttrValues,
      template: artTemplate(rules),
    },
    { componentName: componentNameOf(source.id) },
  );
  // Babel's printer drops the blank line the template writes between the imports and the component.
  return formatTs(code.replace(/\n(?=export function )/, '\n\n'), outputPath, options);
}

function typesModule(): string {
  const declared = new Map<string, readonly SentinelRole[]>();
  for (const group of ART_GROUPS) {
    const rules = ART_RULES[group];
    const roles = rolesOf(rules);
    const previous = declared.get(rules.propsType);
    if (previous !== undefined && previous.join() !== roles.join()) {
      throw new Error(`${rules.propsType} has different roles in two groups`);
    }
    declared.set(rules.propsType, roles);
  }
  return [...declared]
    .map(
      ([name, roles]) =>
        `export type ${name} = { ${roles.map((role) => `${role}: string;`).join(' ')} };`,
    )
    .join('\n');
}

/** The value of an attribute of the source root, as written, or null when it is absent. */
function rootAttribute(text: string, name: string): string | null {
  const match = new RegExp(`<svg[^>]*\\s${name}="([^"]*)"`).exec(text);
  return match?.[1] ?? null;
}

function officeMeta(source: Source): string {
  const crop = rootAttribute(source.text, 'data-crop') ?? '';
  const [width, height] = (rootAttribute(source.text, 'data-spot') ?? '').trim().split(/\s+/);
  const placeholderOf = rootAttribute(source.text, 'data-placeholder-of');
  return `'${source.id}': { crop: ${String(Number(crop))}, spot: [${String(Number(width))}, ${String(Number(height))}], placeholderOf: ${placeholderOf === null ? 'null' : `'${placeholderOf}'`} },`;
}

/**
 * The name the index gives a component. A drawing and its glyph share an id, so the office and pin
 * components are imported under a suffix; the issue icons keep their own names.
 */
function localNameOf(group: ArtGroup, id: string): string {
  const name = componentNameOf(id);
  switch (group) {
    case 'offices':
      return `${name}Art`;
    case 'pins':
      return `${name}Glyph`;
    case 'issues':
      return name;
    default:
      return assertNever(group);
  }
}

function indexModule(byGroup: ReadonlyMap<ArtGroup, readonly Source[]>): string {
  const lines: string[] = [];
  const typeImports = new Set<string>();
  const componentImports: string[] = [];
  const maps: string[] = [];
  for (const group of ART_GROUPS) {
    const sources = byGroup.get(group) ?? [];
    if (sources.length === 0) continue;
    const rules = ART_RULES[group];
    for (const source of sources) {
      const name = componentNameOf(source.id);
      const local = localNameOf(group, source.id);
      componentImports.push(
        `import { ${name === local ? name : `${name} as ${local}`} } from './${group}/${source.id}.tsx';`,
      );
    }
    if (group === 'issues') {
      typeImports.add(rules.propsType);
      const present = new Set(sources.map((source) => source.id));
      const entries = ISSUE_IDS.filter((id) => present.has(id)).map(
        (id) => `'${id}': ${componentNameOf(id)},`,
      );
      maps.push(
        `export const ${rules.mapName} = {\n${entries.join('\n')}\n} as const satisfies Readonly<Record<IssueId, ComponentType<${rules.propsType}>>>;`,
      );
    } else {
      const entries = sources.map((source) => `'${source.id}': ${localNameOf(group, source.id)},`);
      maps.push(`export const ${rules.mapName} = {\n${entries.join('\n')}\n} as const;`);
      if (group === 'offices') {
        maps.push(
          `export const OFFICE_ART_META: Readonly<Record<keyof typeof OFFICE_ART, { crop: number; spot: [number, number]; placeholderOf: string | null }>> = {\n${sources.map(officeMeta).join('\n')}\n};`,
        );
      }
    }
  }
  if ((byGroup.get('issues')?.length ?? 0) > 0) {
    lines.push(
      `import type { ComponentType } from 'react';`,
      `import type { IssueId } from '@citizenrun/shared';`,
    );
  }
  lines.push(...componentImports);
  if (typeImports.size > 0) {
    lines.push(
      `import type { ${[...typeImports].sort((a, b) => a.localeCompare(b, 'en')).join(', ')} } from './types.ts';`,
    );
  }
  lines.push('', ...maps, `export type { GlyphProps, OfficeArtRoles } from './types.ts';`);
  return lines.join('\n');
}

/** Writes `content` unless the file already holds it; returns whether it wrote. */
async function writeIfChanged(path: string, content: string): Promise<boolean> {
  try {
    if ((await readFile(path, 'utf8')) === content) return false;
  } catch (error) {
    if (!isMissing(error)) throw error;
  }
  await mkdir(dirname(path), { recursive: true });
  await writeFile(path, content);
  return true;
}

/** Lints every source, then (only when nothing failed) writes the generated folder under `packageRoot`. */
export async function generateIllustrations(packageRoot: string): Promise<GenerateResult> {
  const byGroup = new Map<ArtGroup, Source[]>();
  const violations: ArtViolation[] = [];
  for (const group of ART_GROUPS) {
    const folder = join(packageRoot, ART_RULES[group].folder);
    const files = await filesOf(folder);
    if (!files.some((file) => file.endsWith('.svg'))) continue;
    const sources: Source[] = [];
    for (const fileName of files) {
      const text = await readFile(join(folder, fileName), 'utf8');
      for (const violation of lintArtSource(group, fileName, text)) {
        violations.push({ ...violation, file: `${group}/${violation.file}` });
      }
      sources.push({ group, id: fileName.replace(/\.svg$/, ''), fileName, text });
    }
    byGroup.set(group, sources);
  }
  if (violations.length > 0) {
    return { written: [], removed: [], violations };
  }

  const options = await prettierOptions();
  const written: string[] = [];
  const removed: string[] = [];
  const write = async (relative: string, content: string): Promise<void> => {
    if (await writeIfChanged(join(packageRoot, relative), content)) {
      written.push(relative);
    }
  };

  for (const group of ART_GROUPS) {
    const sources = byGroup.get(group) ?? [];
    const keep = new Set<string>();
    for (const source of sources) {
      const relative = `${GENERATED}/${group}/${source.id}.tsx`;
      keep.add(`${source.id}.tsx`);
      await write(relative, await componentOf(source, options, join(packageRoot, relative)));
    }
    for (const file of await filesOf(join(packageRoot, GENERATED, group))) {
      if (file.endsWith('.tsx') && !keep.has(file)) {
        await rm(join(packageRoot, GENERATED, group, file));
        removed.push(`${GENERATED}/${group}/${file}`);
      }
    }
  }
  const typesPath = `${GENERATED}/types.ts`;
  await write(typesPath, await formatTs(typesModule(), join(packageRoot, typesPath), options));
  const indexPath = `${GENERATED}/index.ts`;
  await write(
    indexPath,
    await formatTs(indexModule(byGroup), join(packageRoot, indexPath), options),
  );
  return { written, removed, violations: [] };
}

if (process.argv[1] !== undefined && resolve(process.argv[1]) === SCRIPT_PATH) {
  const packageRoot = dirname(dirname(SCRIPT_PATH));
  const result = await generateIllustrations(packageRoot);
  for (const violation of result.violations) {
    process.stderr.write(`${violation.file}: ${violation.rule}: ${violation.message}\n`);
  }
  if (result.violations.length > 0) {
    process.exitCode = 1;
  }
}
