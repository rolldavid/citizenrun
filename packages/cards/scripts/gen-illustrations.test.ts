/** A fixture office types file in the data file's format. */
function officeTypesYaml(records: readonly (readonly [string, string])[]): string {
  return [
    '# Fixture office types.',
    ...records.flatMap(([id, illustration]) => [
      `- id: ${id}`,
      `  name: 'Fixture ${id}'`,
      '  level: county',
      `  illustration: ${illustration}`,
      '  electorate: public',
      `  aliases: ['fixture ${id}']`,
    ]),
    '',
  ].join('\n');
}

async function writeOfficeTypes(
  root: string,
  records: readonly (readonly [string, string])[],
): Promise<{ officeTypesPath: string }> {
  const officeTypesPath = join(root, 'office-types.yaml');
  await writeFile(officeTypesPath, officeTypesYaml(records));
  return { officeTypesPath };
}
// SVGO, SVGR and Prettier over all nineteen sources take a few seconds.
const SLOW = { timeout: 60000 };

const temporary: string[] = [];

async function tempPackage(): Promise<string> {
  const folder = await mkdtemp(join(tmpdir(), 'cards-gen-'));
  temporary.push(folder);
  return folder;
}

async function writeSource(
  root: string,
  group: string,
  fileName: string,
  text: string,
): Promise<void> {
  await mkdir(join(root, 'art', group), { recursive: true });
  await writeFile(join(root, 'art', group, fileName), text);
}

/** Every file under a folder, relative to it, or none when it does not exist. */
async function listAll(folder: string): Promise<string[]> {
  if (!existsSync(folder)) return [];
  const entries = await readdir(folder, { recursive: true, withFileTypes: true });
  return entries
    .filter((entry) => entry.isFile())
    .map((entry) => join(entry.parentPath, entry.name));
}

afterEach(async () => {
  for (const folder of temporary.splice(0)) {
    await rm(folder, { recursive: true, force: true });
  }
});

describe('generateIllustrations', () => {
  it('art sources pass the lint', () => {
    expect(svgFiles('issues')).toHaveLength(19);
    const ids = illustrationIds();
    for (const group of ART_GROUPS) {
      const folder = join(PACKAGE_ROOT, ART_RULES[group].folder);
      for (const file of svgFiles(group)) {
        const text = readFileSync(join(folder, file), 'utf8');
        expect(
          lintArtSource(group, file, text, { illustrationIds: ids }),
          `${group}/${file}`,
        ).toEqual([]);
      }
    }
  });

  it('the generated folder is current', SLOW, async () => {
    const root = await tempPackage();
    await cp(join(PACKAGE_ROOT, 'art'), join(root, 'art'), { recursive: true });
    await cp(GENERATED_FOLDER, join(root, 'src', 'generated'), { recursive: true });
    const result = await generateIllustrations(root, WITH_DATA);
    expect(result.violations).toEqual([]);
    expect(result.written).toEqual([]);
    expect(result.removed).toEqual([]);
  });

  it('a fresh run writes every file and a second run writes none', SLOW, async () => {
    const root = await tempPackage();
    await cp(join(PACKAGE_ROOT, 'art'), join(root, 'art'), { recursive: true });
    const first = await generateIllustrations(root, WITH_DATA);
    expect(first.written).toHaveLength(SOURCE_COUNT + 3);
    expect(first.written).toContain('src/generated/issues/rent-housing.tsx');
    expect(first.written).toContain('src/generated/types.ts');
    expect(first.written).toContain('src/generated/index.ts');
    expect(first.written).toContain('src/generated/office-type-illustrations.ts');
    for (const file of first.written) {
      const fresh = await readFile(join(root, file), 'utf8');
      expect(fresh, file).toBe(await readFile(join(PACKAGE_ROOT, file), 'utf8'));
    }
    const second = await generateIllustrations(root, WITH_DATA);
    expect(second.written).toEqual([]);
  });

  it('a violation writes nothing', async () => {
    const root = await tempPackage();
    await writeSource(
      root,
      'issues',
      'climate.svg',
      readFileSync(join(ISSUES_FOLDER, 'climate.svg'), 'utf8'),
    );
    const hostile = readFileSync(join(ISSUES_FOLDER, 'schools.svg'), 'utf8').replace(
      'fill="#111111"',
      'fill="#111111" stroke="#111111"',
    );
    await writeSource(root, 'issues', 'schools.svg', hostile);
    const result = await generateIllustrations(root, WITH_DATA);
    expect(result.violations).toHaveLength(1);
    expect(result.violations[0]).toMatchObject({ file: 'issues/schools.svg', rule: 'forbidden' });
    expect(result.written).toEqual([]);
    expect(await listAll(join(root, 'src', 'generated'))).toEqual([]);
  });

  it('a removed source removes its component', SLOW, async () => {
    const root = await tempPackage();
    await cp(join(PACKAGE_ROOT, 'art'), join(root, 'art'), { recursive: true });
    await cp(GENERATED_FOLDER, join(root, 'src', 'generated'), { recursive: true });
    const extra = join(root, 'src', 'generated', 'issues', 'old-name.tsx');
    await writeFile(extra, `${HEADER}\nexport function OldName() {\n  return null;\n}\n`);
    const result = await generateIllustrations(root, WITH_DATA);
    expect(result.removed).toEqual(['src/generated/issues/old-name.tsx']);
    expect(existsSync(extra)).toBe(false);
    expect(result.written).toEqual([]);
  });

  it('the template', async () => {
    const root = await tempPackage();
    await writeSource(
      root,
      'issues',
      'climate.svg',
      readFileSync(join(ISSUES_FOLDER, 'climate.svg'), 'utf8'),
    );
    const result = await generateIllustrations(root, WITH_DATA);
    expect(result.violations).toEqual([]);
    const text = await readFile(join(root, 'src', 'generated', 'issues', 'climate.tsx'), 'utf8');
    expect(text.split('\n')[0]).toBe(HEADER);
    expect(text).toContain("import { G, Path } from '@citizenrun/cards/primitives';");
    expect(text).toContain("import type { GlyphProps } from '../types.ts';");
    expect(text).toContain('export function Climate(props: GlyphProps)');
    expect(text).not.toContain('Svg');
    expect(text).not.toContain('viewBox');
    expect(text).not.toContain('react-native-svg');
    expect(text).not.toContain('xmlns');
    // SVGO kept the sentinel whole, so every fill became the prop and no color is left.
    const fills = [...text.matchAll(/\bfill=(\{[^}]*\}|"[^"]*")/g)].map((match) => match[1]);
    expect(fills.length).toBeGreaterThan(0);
    expect(new Set(fills)).toEqual(new Set(['{props.fill}']));
    expect(text).not.toMatch(/#[0-9A-Fa-f]{3,6}\b/);
    expect(text).toContain('fillRule="evenodd"');
    expect(text.endsWith('\n')).toBe(true);
    expect(text).not.toContain('\r');
  });

  it('the index is keyed by ISSUE_IDS', () => {
    const text = readFileSync(join(GENERATED_FOLDER, 'index.ts'), 'utf8');
    const block = /export const ISSUE_ICONS = \{([^}]*)\}/.exec(text)?.[1] ?? '';
    const keys = [...block.matchAll(/^\s*'?([a-z0-9-]+)'?:/gm)].map((match) => match[1]);
    expect(keys).toEqual([...ISSUE_IDS]);
    for (const id of ISSUE_IDS) {
      expect(block).toContain(`${componentNameOf(id)},`);
    }
    expect(text).not.toMatch(/\bISSUE_IDS\b/);
    if (svgFiles('offices').length === 0) {
      expect(text).not.toMatch(/OFFICE_ART|PIN_GLYPHS/);
    }
  });

  it('every generated file carries the header', async () => {
    const files = await listAll(GENERATED_FOLDER);
    expect(files).toHaveLength(SOURCE_COUNT + 3);
    for (const file of files) {
      expect(readFileSync(file, 'utf8').startsWith(`${HEADER}\n`), file).toBe(true);
    }
  });

  it('the prop types come from the rules', () => {
    expect(readFileSync(join(GENERATED_FOLDER, 'types.ts'), 'utf8')).toBe(
      [
        HEADER,
        'export type OfficeArtRoles = { ink: string; paper: string; tone: string; spot: string };',
        'export type GlyphProps = { fill: string };',
        '',
      ].join('\n'),
    );
  });

  it('office and pin maps', async () => {
    const root = await tempPackage();
    await writeSource(root, 'offices', 'county-treasurer.svg', TREASURER);
    await writeSource(root, 'pins', 'county-treasurer.svg', TREASURER_PIN);
    const result = await generateIllustrations(
      root,
      await writeOfficeTypes(root, [['county-treasurer', 'county-treasurer']]),
    );
    expect(result.violations).toEqual([]);
    const art = await readFile(
      join(root, 'src', 'generated', 'offices', 'county-treasurer.tsx'),
      'utf8',
    );
    expect(art).toContain('export function CountyTreasurer(props: OfficeArtRoles)');
    expect(art).toContain("import type { OfficeArtRoles } from '../types.ts';");
    // SVGO turns the rectangles into paths, so the drawing imports only the primitives it still uses.
    expect(art).toContain("import { Circle, G, Path } from '@citizenrun/cards/primitives';");
    for (const role of ['ink', 'paper', 'tone', 'spot']) {
      expect(art).toContain(`fill={props.${role}}`);
    }
    expect(art).not.toMatch(/#[0-9A-Fa-f]{6}\b/);
    expect(art).not.toContain('Svg');
    expect(art).not.toContain('viewBox');
    const glyph = await readFile(
      join(root, 'src', 'generated', 'pins', 'county-treasurer.tsx'),
      'utf8',
    );
    expect(glyph).toContain('export function CountyTreasurer(props: GlyphProps)');
    const index = await readFile(join(root, 'src', 'generated', 'index.ts'), 'utf8');
    expect(index).toContain(
      "import { CountyTreasurer as OfficesCountyTreasurer } from './offices/county-treasurer.tsx';",
    );
    expect(index).toContain(
      "import { CountyTreasurer as PinsCountyTreasurer } from './pins/county-treasurer.tsx';",
    );
    expect(index).toContain("import type { GlyphProps, OfficeArtRoles } from './types.ts';");
    expect(index).toContain("export const OFFICE_ART_IDS = ['county-treasurer'] as const;");
    expect(index).toContain('export type OfficeArtId = (typeof OFFICE_ART_IDS)[number];');
    expect(index).toContain(
      "export const OFFICE_ART = {\n  'county-treasurer': OfficesCountyTreasurer,\n} as const satisfies Readonly<Record<OfficeArtId, ComponentType<OfficeArtRoles>>>;",
    );
    expect(index).toContain(
      "export const PIN_GLYPHS = {\n  'county-treasurer': PinsCountyTreasurer,\n} as const satisfies Readonly<Record<OfficeArtId, ComponentType<GlyphProps>>>;",
    );
    expect(index).toContain('export const OFFICE_ART_META = {');
    expect(index).toContain(
      "'county-treasurer': { crop: 80, spot: [8, 24], placeholderOf: null },",
    );
    expect(index).toContain("import type { ComponentType } from 'react';");
    expect(index).not.toContain('ISSUE_ICONS');
    expect(index).not.toContain('IssueId');
  });

  it("a placeholder's meta names its relative", async () => {
    const root = await tempPackage();
    await writeSource(root, 'offices', 'county-treasurer.svg', TREASURER);
    await writeSource(
      root,
      'offices',
      'state-treasurer.svg',
      TREASURER.replace(
        'data-spot="8 24"',
        'data-spot="8 24" data-placeholder-of="county-treasurer"',
      ),
    );
    await writeSource(root, 'pins', 'county-treasurer.svg', TREASURER_PIN);
    await writeSource(root, 'pins', 'state-treasurer.svg', TREASURER_PIN);
    const result = await generateIllustrations(
      root,
      await writeOfficeTypes(root, [
        ['county-treasurer', 'county-treasurer'],
        ['state-treasurer', 'state-treasurer'],
      ]),
    );
    expect(result.violations).toEqual([]);
    const index = await readFile(join(root, 'src', 'generated', 'index.ts'), 'utf8');
    expect(index).toContain(
      "'state-treasurer': { crop: 80, spot: [8, 24], placeholderOf: 'county-treasurer' },",
    );
    expect(index).toContain(
      "export const OFFICE_ART_IDS = ['county-treasurer', 'state-treasurer'] as const;",
    );
  });

  it('an office file that is no illustration stops the run', async () => {
    const root = await tempPackage();
    await writeSource(root, 'offices', 'county-treasurer.svg', TREASURER);
    const result = await generateIllustrations(
      root,
      await writeOfficeTypes(root, [['us-senate', 'congress']]),
    );
    expect(result.violations).toEqual([
      expect.objectContaining({ file: 'offices/county-treasurer.svg', rule: 'id' }),
    ]);
    expect(await listAll(join(root, 'src', 'generated'))).toEqual([]);
  });

  it('writes the office-type map', async () => {
    const root = await tempPackage();
    const result = await generateIllustrations(
      root,
      await writeOfficeTypes(root, [
        ['us-senate', 'congress'],
        ['us-house', 'congress'],
        ['county-treasurer', 'county-treasurer'],
      ]),
    );
    expect(result.violations).toEqual([]);
    expect(result.written).toContain('src/generated/office-type-illustrations.ts');
    const text = await readFile(
      join(root, 'src', 'generated', 'office-type-illustrations.ts'),
      'utf8',
    );
    expect(text.split('\n')[0]).toBe(HEADER);
    const keys = [...text.matchAll(/^\s*'?([a-z0-9-]+)'?: '([a-z0-9-]+)',$/gm)].map((match) => [
      match[1],
      match[2],
    ]);
    expect(keys).toEqual([
      ['us-senate', 'congress'],
      ['us-house', 'congress'],
      ['county-treasurer', 'county-treasurer'],
    ]);
    expect(text).toContain('} as const satisfies Readonly<Record<string, string>>;');
  });

  it('the committed office-type map follows the data file', () => {
    const text = readFileSync(join(GENERATED_FOLDER, 'office-type-illustrations.ts'), 'utf8');
    const pairs = [...text.matchAll(/^\s*'?([a-z0-9-]+)'?: '([a-z0-9-]+)',$/gm)].map((match) => ({
      officeTypeId: match[1],
      illustration: match[2],
    }));
    expect(pairs).toEqual(readOfficeTypeIllustrations(readFileSync(OFFICE_TYPES_PATH, 'utf8')));
  });
});

describe('readOfficeTypeIllustrations', () => {
  it('reads the office types', () => {
    expect(
      readOfficeTypeIllustrations(
        officeTypesYaml([
          ['us-senate', 'congress'],
          ['us-house', 'congress'],
          ['county-treasurer', 'county-treasurer'],
        ]),
      ),
    ).toEqual([
      { officeTypeId: 'us-senate', illustration: 'congress' },
      { officeTypeId: 'us-house', illustration: 'congress' },
      { officeTypeId: 'county-treasurer', illustration: 'county-treasurer' },
    ]);
  });

  it('reads the data file', () => {
    const officeTypes = readOfficeTypeIllustrations(readFileSync(OFFICE_TYPES_PATH, 'utf8'));
    expect(officeTypes).toHaveLength(42);
    expect(new Set(officeTypes.map((officeType) => officeType.illustration)).size).toBe(39);
  });

  it('refuses a record with no illustration', () => {
    const text = officeTypesYaml([
      ['us-senate', 'congress'],
      ['governor', 'governor'],
    ]).replace('  illustration: governor\n', '');
    expect(() => readOfficeTypeIllustrations(text)).toThrow('line 8');
  });

  it('refuses a record with two illustrations', () => {
    const text = officeTypesYaml([['us-senate', 'congress']]).replace(
      '  electorate: public',
      '  illustration: governor\n  electorate: public',
    );
    expect(() => readOfficeTypeIllustrations(text)).toThrow('line 6');
  });

  it('refuses a repeated id', () => {
    const text = officeTypesYaml([
      ['us-senate', 'congress'],
      ['us-senate', 'congress'],
    ]);
    expect(() => readOfficeTypeIllustrations(text)).toThrow('line 8');
  });

  it('refuses a changed format', () => {
    const records = officeTypesYaml([['us-senate', 'congress']]);
    expect(() =>
      readOfficeTypeIllustrations(records.replace('- id: us-senate', '- { id: us-senate }')),
    ).toThrow('line 2');
    expect(() =>
      readOfficeTypeIllustrations(
        records.replace('  illustration: congress', '  illustration: Congress'),
      ),
    ).toThrow('line 5');
    expect(() =>
      readOfficeTypeIllustrations(
        records.replace('  illustration: congress', '    illustration: congress'),
      ),
    ).toThrow('line 5');
  });

  it('refuses a file with no record', () => {
    expect(() => readOfficeTypeIllustrations('# nothing here\n')).toThrow('no office type');
  });
});
