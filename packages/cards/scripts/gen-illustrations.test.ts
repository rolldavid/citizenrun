const PACKAGE_ROOT = join(import.meta.dirname, '..');
const ISSUES_FOLDER = join(PACKAGE_ROOT, 'art', 'issues');
const GENERATED_FOLDER = join(PACKAGE_ROOT, 'src', 'generated');
const HEADER = '// Generated by pnpm cards:gen. Do not edit.';
const OFFICE_TYPES_PATH = join(PACKAGE_ROOT, '..', '..', 'data', 'office-types.yaml');
const WITH_DATA = { officeTypesPath: OFFICE_TYPES_PATH };

/** The office types file's illustration ids. */
function illustrationIds(): ReadonlySet<string> {
  const officeTypes = readOfficeTypeIllustrations(readFileSync(OFFICE_TYPES_PATH, 'utf8'));
  return new Set(officeTypes.map((officeType) => officeType.illustration));
}

/** The `.svg` files of one group's source folder, or none when it does not exist. */
function svgFiles(group: (typeof ART_GROUPS)[number]): string[] {
  const folder = join(PACKAGE_ROOT, ART_RULES[group].folder);
  return existsSync(folder) ? readdirSync(folder).filter((file) => file.endsWith('.svg')) : [];
}

const SOURCE_COUNT = ART_GROUPS.reduce((count, group) => count + svgFiles(group).length, 0);

