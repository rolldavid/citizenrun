// B-attribution: the bundle's ATTRIBUTION.md, the root ATTRIBUTION.md and the source credits, all
// from data/sources.yaml (D-015, D-335, D-354, D-537).
import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import { BRAND } from '@citizenrun/shared';
import type { BundleManifest } from '@citizenrun/shared';
import { REGISTER_FILES, sourceHosts } from '../lib/data-files.ts';
import type { BoundarySource, SourceEntry } from '../lib/data-files.ts';
import { dataDir } from '../lib/paths.ts';
import { parseYamlWith } from '../lib/yaml.ts';
import type { AssembledRows } from './assemble.ts';

export type SourcesFile = readonly SourceEntry[];
export type SourceCredit = { name: string; url: string | null };

export const LICENCE_PARAGRAPH =
  'The compiled data in this bundle is licensed under the Creative Commons Attribution 4.0 ' +
  'International licence (CC BY 4.0): https://creativecommons.org/licenses/by/4.0/legalcode. ' +
  'The legal code is also in the file data/LICENSE of the source repository.';

export const PHOTO_SENTENCE =
  'Photos and other third-party media are outside the data licence and keep their own licences; ' +
  "each photo's author, licence and source are given with it.";

export const ROOT_FIRST_LINE = '<!-- Generated by pnpm gen:credits from data/sources.yaml. -->';

/** An entry of the manifest's datasets with no entry in data/sources.yaml. */
export class AttributionSourceMissing extends Error {
  override readonly name = 'AttributionSourceMissing';

  constructor(id: string) {
    super(`the dataset ${id} has no entry in data/sources.yaml`);
  }
}

function readSources(): SourcesFile {
  const file = REGISTER_FILES.sources.file;
  const text = readFileSync(join(dataDir(), file), 'utf8');
  return parseYamlWith(text, file, REGISTER_FILES.sources.schema);
}

function creditName(entry: SourceEntry): string {
  return entry.attribution ?? entry.publisher;
}

function originUrl(url: string): string | null {
  try {
    const parsed = new URL(url);
    return parsed.protocol === 'https:' ? `${parsed.origin}/` : null;
  } catch {
    return null;
  }
}

/**
 * One credit per `dataset` and `photo_source` entry of data/sources.yaml that is not forbidden, in
 * the file's order: the entry's attribution line, else its publisher, and the origin of its URL.
 */
export function sourceCredits(sources: SourcesFile = readSources()): readonly SourceCredit[] {
  return sources
    .filter(
      (entry) => (entry.kind === 'dataset' || entry.kind === 'photo_source') && !entry.forbidden,
    )
    .map((entry) => ({ name: creditName(entry), url: originUrl(entry.url) }));
}

function hostOf(url: string | null): string | null {
  if (url === null) return null;
  try {
    return new URL(url).hostname.toLowerCase();
  } catch {
    return null;
  }
}

/**
 * The hosts of every `source_url` in the bundle's proof (field_meta, office powers, filing tracks,
 * elections and eligibility), and the host of each boundary layer whose `ward:` districts the
 * bundle carries.
 */
export function usedHosts(
  rows: AssembledRows,
  boundarySources: readonly BoundarySource[],
): ReadonlySet<string> {
  const hosts = new Set<string>();
  const add = (url: string | null) => {
    const host = hostOf(url);
    if (host !== null) hosts.add(host);
  };
  const metas = (map: Readonly<Record<string, { source_url: string | null }>>) => {
    for (const meta of Object.values(map)) add(meta.source_url);
  };
  for (const table of [
    'jurisdictions',
    'districts',
    'offices',
    'elections',
    'filing_tracks',
  ] as const) {
    for (const row of rows[table]) metas(row.field_meta);
  }
  for (const power of rows.office_powers) add(power.source_url);
  for (const track of rows.filing_tracks) add(track.source_url);
  for (const office of rows.offices) {
    for (const item of office.eligibility ?? []) add(item.source_url);
  }
  const wardPlaces = new Set(
    rows.districts
      .filter((district) => district.source_key.startsWith('ward:'))
      .map((district) => district.source_key.split(':')[1]),
  );
  for (const layer of boundarySources) {
    if (wardPlaces.has(layer.place_geoid)) add(layer.url);
  }
  return hosts;
}

function usable(entry: SourceEntry): boolean {
  return !entry.forbidden;
}

/** The bundle's ATTRIBUTION.md (B-attribution). */
export function renderBundleAttribution(
  manifest: BundleManifest,
  sources: SourcesFile,
  hosts: ReadonlySet<string>,
): string {
  const byId = new Map(sources.map((entry) => [entry.id, entry]));
  for (const id of Object.keys(manifest.datasets)) {
    if (!byId.has(id)) throw new AttributionSourceMissing(id);
  }
  const datasets = sources
    .filter((entry) => Object.hasOwn(manifest.datasets, entry.id))
    .map((entry) => {
      const used = manifest.datasets[entry.id];
      return (
        `- ${creditName(entry)}. ${entry.name}, edition ${used?.edition ?? ''}, downloaded ` +
        `${used?.downloaded_on ?? ''}. Licence: ${entry.licence_spdx ?? 'no licence stated'}. ` +
        `Source: ${used?.source_url ?? entry.url}`
      );
    });
  const local = sources
    .filter(
      (entry) =>
        (entry.kind === 'crawl_host' || entry.kind === 'adapter') &&
        usable(entry) &&
        sourceHosts(entry).some((host) => hosts.has(host)),
    )
    .map((entry) => `- ${creditName(entry)}. ${entry.name}. Source: ${entry.url}`);
  const photos = sources
    .filter((entry) => entry.kind === 'photo_source' && usable(entry))
    .map((entry) => `- ${creditName(entry)}. ${entry.name}. Source: ${entry.url}`);
  return [
    '# Data attribution',
    '',
    `${BRAND.displayName} data bundle ${manifest.version}, built ${manifest.created_at.slice(0, 10)}.`,
    '',
    LICENCE_PARAGRAPH,
    '',
    '## Datasets',
    '',
    ...(datasets.length === 0 ? ['None in this bundle.'] : datasets),
    '',
    '## State and local sources',
    '',
    ...(local.length === 0 ? ['None in this bundle.'] : local),
    '',
    '## Photo sources',
    '',
    ...photos,
    '',
    PHOTO_SENTENCE,
    '',
  ].join('\n');
}

/** The repository's root ATTRIBUTION.md, written by `pnpm gen:credits`. */
export function renderRootAttribution(sources: SourcesFile): string {
  const credits = sourceCredits(sources).map((credit) =>
    credit.url === null ? `- ${credit.name}` : `- ${credit.name}: ${credit.url}`,
  );
  return [
    ROOT_FIRST_LINE,
    '',
    '# Data attribution',
    '',
    LICENCE_PARAGRAPH,
    '',
    '## Sources',
    '',
    ...credits,
    '',
  ].join('\n');
}
