// `pnpm gen:credits`: writes SOURCE_CREDITS and the root ATTRIBUTION.md from data/sources.yaml.
// Each file is written only when its content changed, so a clean tree shows no drift.
import { readFile, writeFile } from 'node:fs/promises';
import { join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { loadSources } from '../lib/data-files.ts';
import { repoRoot } from '../lib/paths.ts';
import { renderRootAttribution, sourceCredits } from './attribution.ts';
import type { SourceCredit } from './attribution.ts';

export const CREDITS_PATH = join('packages', 'shared', 'src', 'legal', 'source-credits.ts');
export const ROOT_ATTRIBUTION_PATH = 'ATTRIBUTION.md';

function quoted(value: string): string {
  return `'${value.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;
}

/** The text of `packages/shared/src/legal/source-credits.ts`. */
export function renderSourceCredits(credits: readonly SourceCredit[]): string {
  const lines = credits.map(
    (credit) =>
      `  { name: ${quoted(credit.name)}, url: ${credit.url === null ? 'null' : quoted(credit.url)} },`,
  );
  return [
    '// Generated by pnpm gen:credits from data/sources.yaml. Do not edit.',
    'export const SOURCE_CREDITS: readonly { name: string; url: string | null }[] = [',
    ...lines,
    '] as const;',
    '',
  ].join('\n');
}

async function writeIfChanged(path: string, content: string): Promise<boolean> {
  let before: string | null = null;
  try {
    before = await readFile(path, 'utf8');
  } catch {
    before = null;
  }
  if (before === content) return false;
  await writeFile(path, content, 'utf8');
  return true;
}

export async function main(): Promise<number> {
  const root = repoRoot();
  const sources = await loadSources();
  const credits = await writeIfChanged(
    join(root, CREDITS_PATH),
    renderSourceCredits(sourceCredits(sources)),
  );
  const attribution = await writeIfChanged(
    join(root, ROOT_ATTRIBUTION_PATH),
    renderRootAttribution(sources),
  );
  process.stdout.write(
    `gen:credits: ${CREDITS_PATH} ${credits ? 'written' : 'unchanged'}, ${ROOT_ATTRIBUTION_PATH} ${attribution ? 'written' : 'unchanged'}\n`,
  );
  return 0;
}

const entry = process.argv[1];
if (entry !== undefined && resolve(entry) === fileURLToPath(import.meta.url)) {
  process.exitCode = await main();
}
