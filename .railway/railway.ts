// .railway/railway.ts
// Railway resources of the environments `staging` and `production` (D-020, D-026).
// OPS-railway-file. Changed only through
// .github/workflows/railway-config.yml (D-132). Never holds a secret value (D-116, D-133).
import {
  bucket,
  defineRailway,
  github,
  image,
  preserve,
  project,
  ref,
  service,
  volume,
} from 'railway/iac';
import { BRAND } from '../packages/shared/src/brand.ts';
import type { BrandVariant } from '../packages/shared/src/brand.ts';

const REGION = 'us-east4-eqdc4a'; // D-135; a service's region is the key of its replicas (D-848)
const BUCKET_REGION = 'iad'; // D-025, D-135; always passed (D-130)
const POSTGIS_IMAGE =
  'postgis/postgis:17-3.7@sha256:d09654ba11d2a091e220e561c32b17ad00b0858045bc29741e7bcedcd9c4ee60'; // D-021, D-136; equals docker/images.json "postgis"
const PORT = 8080; // D-130
const GIB = 1073741824;
const MIGRATE = 'node packages/db/dist/migrate.js'; // D-141: one executable, no shell operators
// D-140: one api replica in each environment until a change raises it.
const API_REPLICAS = { staging: 1, production: 1 } as const;
const APP_WATCH = ['/**', '!/docs/**', '!/pipeline/**', '!/ml/**', '!/data/**', '!/.github/**']; // D-022
const BACKUP_WATCH = [
  '/apps/worker/src/backup/**',
  '/apps/worker/package.json',
  '/packages/shared/**',
  '/docker/backup.Dockerfile',
  '/scripts/build-service.ts',
  '/package.json',
  '/pnpm-lock.yaml',
  '/pnpm-workspace.yaml',
]; // PC9-07
// D-574: true for an environment only once D-100 spike 13 has passed there.
const APPLE_WEB_SIGN_IN: Readonly<Record<EnvName, boolean>> = { staging: false, production: false };

type EnvName = 'staging' | 'production';
type BucketPrefix = 'MEDIA' | 'DATA' | 'BACKUPS' | 'LEGAL';

function required(value: string | null, key: string): string {
  if (value === null) throw new Error(`brand.json: ${key} is not set`);
  return value;
}

/** Replicas in the one region, in the form `railway config pull` writes (D-131, D-848). */
function inRegion(count: number): Record<string, number> {
  return { [REGION]: count };
}

function bucketVars(prefix: BucketPrefix, target: ReturnType<typeof bucket>) {
  return {
    [`${prefix}_BUCKET`]: ref(target, 'BUCKET'),
    [`${prefix}_ENDPOINT`]: ref(target, 'ENDPOINT'),
    [`${prefix}_REGION`]: ref(target, 'REGION'),
    [`${prefix}_ACCESS_KEY_ID`]: ref(target, 'ACCESS_KEY_ID'),
    [`${prefix}_SECRET_ACCESS_KEY`]: ref(target, 'SECRET_ACCESS_KEY'),
  };
}

export default defineRailway((ctx) => {
  const name = ctx.environment;
  if (name !== 'staging' && name !== 'production')
    throw new Error(`railway.ts: unknown environment ${String(name)}`);
  const env: EnvName = name;
  const variant: BrandVariant = BRAND.variants[env]; // read as nullable: brand.json changes in activations
  const host = required(variant.host, `variants.${env}.host`);
  const adminHost = required(variant.adminHost, `variants.${env}.adminHost`); // D-798: the admin service's host (D-801)
  // The custom domains on these hosts are added by the bootstrap, not here (D-849).
  const repo = required(BRAND.github.repository, 'github.repository');
  const source = github(repo, { branch: env, checkSuites: true }); // D-102, D-134

  const pgdata = volume('pgdata', { region: REGION, sizeMB: 50000 }); // D-137
  const postgres = service('postgres', {
    source: image(POSTGIS_IMAGE), // no GitHub source (D-136)
    volumeMounts: { '/var/lib/postgresql/data': pgdata },
    env: {
      POSTGRES_DB: 'citizenrun',
      POSTGRES_USER: 'citizenrun',
      POSTGRES_PASSWORD: preserve(), // sealed, generated by the bootstrap (D-131)
      PGDATA: '/var/lib/postgresql/data/pgdata',
      RAILWAY_SHM_SIZE_BYTES: '536870912', // D-136
      // D-133's superuser URL; no service references it (OPS-db-roles).
      DATABASE_URL:
        'postgresql://${{POSTGRES_USER}}:${{POSTGRES_PASSWORD}}@${{RAILWAY_PRIVATE_DOMAIN}}:5432/${{POSTGRES_DB}}',
      API_DB_PASSWORD: preserve(), // sealed, OPS-db-roles
      WORKER_DB_PASSWORD: preserve(), // sealed
      BACKUP_DB_PASSWORD: preserve(), // sealed
      ADMIN_DB_PASSWORD: preserve(), // sealed (D-801)
      API_DATABASE_URL:
        'postgresql://app_api:${{API_DB_PASSWORD}}@${{RAILWAY_PRIVATE_DOMAIN}}:5432/${{POSTGRES_DB}}',
      WORKER_DATABASE_URL:
        'postgresql://app_worker:${{WORKER_DB_PASSWORD}}@${{RAILWAY_PRIVATE_DOMAIN}}:5432/${{POSTGRES_DB}}',
      BACKUP_DATABASE_URL:
        'postgresql://app_backup:${{BACKUP_DB_PASSWORD}}@${{RAILWAY_PRIVATE_DOMAIN}}:5432/${{POSTGRES_DB}}',
      ADMIN_DATABASE_URL:
        'postgresql://app_admin:${{ADMIN_DB_PASSWORD}}@${{RAILWAY_PRIVATE_DOMAIN}}:5432/${{POSTGRES_DB}}', // D-801
    },
    replicas: inRegion(1),
    deploy: {
      restartPolicyType: 'ALWAYS',
      limitOverride: { containers: { cpu: 2, memoryBytes: 4 * GIB } }, // D-139
    },
  });

  const media = bucket('media', { region: BUCKET_REGION });
  const data = bucket('data', { region: BUCKET_REGION });
  const backups = bucket('backups', { region: BUCKET_REGION });

  const api = service('api', {
    source,
    build: {
      builder: 'DOCKERFILE',
      dockerfilePath: 'docker/api.Dockerfile',
      watchPatterns: APP_WATCH,
    }, // D-022
    preDeploy: MIGRATE, // D-023
    healthcheck: '/readyz', // D-024, D-145
    healthcheckTimeout: 60,
    replicas: inRegion(API_REPLICAS[env]),
    env: {
      APP_ENV: env,
      PORT: String(PORT),
      LOG_LEVEL: 'info',
      DATABASE_URL: postgres.env.API_DATABASE_URL, // role app_api (OPS-db-roles)
      PUBLIC_URL: `https://${host}`,
      ...(env === 'staging' ? { ENABLE_DEV_ROUTES: 'true' } : {}), // PC9-10
      ...bucketVars('MEDIA', media),
      APP_SECRET: preserve(), // sealed; generated by the bootstrap (D-131)
      RESEND_API_KEY: preserve(), // sealed; the API's mailers (D-428, D-557)
      EMAIL_FROM: preserve(), // OPS-dns-email
      ADMIN_EMAILS: preserve(), // D-557
      CLIENT_IP_HEADER: 'x-real-ip', // D-240, D-848
      APPLE_TEAM_ID: preserve(),
      APPLE_KEY_ID: preserve(),
      APPLE_PRIVATE_KEY: preserve(), // sealed
      APPLE_BUNDLE_ID: variant.iosBundleId,
      ...(variant.appleServicesId === null ? {} : { APPLE_SERVICES_ID: variant.appleServicesId }), // D-574
      GOOGLE_CLIENT_IDS: preserve(),
      EXPO_PUBLIC_GOOGLE_WEB_CLIENT_ID: preserve(), // a build argument of the web export
      ...(variant.appleServicesId !== null && APPLE_WEB_SIGN_IN[env]
        ? { EXPO_PUBLIC_APPLE_SERVICES_ID: variant.appleServicesId }
        : {}), // D-574
      APP_SECRET_PREVIOUS: preserve(), // sealed; absent until the first APP_SECRET rotation
      REVIEW_SIGNIN_EMAILS: preserve(),
      REVIEW_SIGNIN_CODE: preserve(), // sealed; present exactly when REVIEW_SIGNIN_EMAILS is
    },
    deploy: {
      restartPolicyType: 'ALWAYS', // D-024
      overlapSeconds: 15,
      drainingSeconds: 30,
      preDeployTimeoutSeconds: 600, // D-141
      limitOverride: { containers: { cpu: 1, memoryBytes: 1 * GIB } }, // D-139, per replica
    },
  });

  const worker = service('worker', {
    source,
    build: {
      builder: 'DOCKERFILE',
      dockerfilePath: 'docker/worker.Dockerfile',
      watchPatterns: APP_WATCH,
    },
    preDeploy: MIGRATE, // D-023: both services migrate, behind the advisory lock
    replicas: inRegion(1), // D-140
    env: {
      APP_ENV: env,
      LOG_LEVEL: 'info',
      DATABASE_URL: postgres.env.WORKER_DATABASE_URL, // role app_worker
      PUBLIC_URL: `https://${host}`,
      RESEND_API_KEY: preserve(), // sealed; the dead-letter email (D-238)
      EMAIL_FROM: preserve(),
      ADMIN_EMAILS: preserve(),
      ...bucketVars('BACKUPS', backups), // D-028: the dump-age check
      APP_SECRET: preserve(), // sealed; same value as on api
      ...bucketVars('MEDIA', media), // media jobs and deletes
      APPLE_TEAM_ID: preserve(), // D-423: the account deletion revokes Apple tokens
      APPLE_KEY_ID: preserve(), // D-423
      APPLE_PRIVATE_KEY: preserve(), // D-423; sealed
      APP_SECRET_PREVIOUS: preserve(), // sealed; absent until the first APP_SECRET rotation
      EMAIL_MONTHLY_QUOTA: '3000', // D-444
      EMAIL_DAILY_QUOTA: '100', // D-444
    },
    deploy: {
      restartPolicyType: 'ALWAYS',
      drainingSeconds: 120, // D-024
      preDeployTimeoutSeconds: 600,
      limitOverride: { containers: { cpu: 4, memoryBytes: 3 * GIB } }, // D-139
    },
  });

  const backup = service('backup', {
    source,
    build: {
      builder: 'DOCKERFILE',
      dockerfilePath: 'docker/backup.Dockerfile',
      watchPatterns: BACKUP_WATCH,
    }, // D-144
    env: {
      APP_ENV: env,
      LOG_LEVEL: 'info',
      DATABASE_URL: postgres.env.BACKUP_DATABASE_URL, // read-only role app_backup (OPS-db-roles)
      ...bucketVars('BACKUPS', backups),
      BACKUP_PUBLIC_KEY: preserve(), // OPS-backup-envelope; a public key, not a secret
    },
    replicas: inRegion(1),
    deploy: {
      cronSchedule: '0 8 * * *', // D-144, UTC
      restartPolicyType: 'NEVER',
      limitOverride: { containers: { cpu: 1, memoryBytes: 1 * GIB } }, // PC9-07
    },
  });

  // OPS-svc-admin (D-801). No source: deployed with `railway up`, never by a push of this repository.
  const admin = service('admin', {
    build: { builder: 'DOCKERFILE', dockerfilePath: 'docker/admin.Dockerfile' },
    healthcheck: '/readyz', // holds a deploy until every migration it was built against is applied
    healthcheckTimeout: 60,
    replicas: inRegion(1),
    env: {
      APP_ENV: env,
      PORT: String(PORT),
      LOG_LEVEL: 'info',
      DATABASE_URL: postgres.env.ADMIN_DATABASE_URL, // role app_admin (OPS-db-roles)
      PUBLIC_URL: `https://${host}`,
      ADMIN_URL: `https://${adminHost}`,
      ...bucketVars('MEDIA', media), // person photo uploads (D-143)
      APP_SECRET: preserve(), // sealed; same value as on api and worker
      RESEND_API_KEY: preserve(), // sealed; the sign-in code email (D-557)
      EMAIL_FROM: preserve(), // OPS-dns-email
      ADMIN_EMAILS: preserve(), // D-557
      CLIENT_IP_HEADER: 'x-real-ip', // D-240, D-848
      APP_SECRET_PREVIOUS: preserve(), // sealed; absent until the first APP_SECRET rotation
    },
    deploy: {
      restartPolicyType: 'ALWAYS',
      overlapSeconds: 0, // no overlap (D-801)
      drainingSeconds: 30,
      limitOverride: { containers: { cpu: 1, memoryBytes: 1 * GIB } }, // D-139
    },
  });

  return project(BRAND.slug, {
    resources: [postgres, media, data, backups, api, worker, backup, admin],
  });
});
